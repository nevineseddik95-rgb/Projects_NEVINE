const catalogs: Record<Language, Record<string, string>> = { en, fr };

export function translate(language: Language, key: string, params: TranslationParams = {}): string {
  const template = catalogs[language][key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

export function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem('charm_language');
    const explicitlyChosen = localStorage.getItem('charm_language_explicit') === '1';
    if (explicitlyChosen && (saved === 'en' || saved === 'fr')) return saved;
  } catch {
    // Storage can be unavailable in private browsing.
  }
  return 'fr';
}

